#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char	*t;
	int		i;
	int		len;

	i = 0;
	len = ft_strlen(s);
	t = malloc(sizeof(char) * len + 1);
	if (t == NULL)
		return (NULL);
	while (s[i])
	{
		t[i] = f(i, s[i]);
		i++;
	}
	t[i] = '\0';
	return (t);
}
